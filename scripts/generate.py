#!/usr/bin/env python3
"""Generate operation definitions from the reviewed catalog. No network required."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
ops=json.loads((root/'api/operations.json').read_text())['operations']
def camel(name):
 p=name.split('_');return p[0]+''.join(x.title() for x in p[1:])
out=['// Generated by scripts/generate.py. Edit api/operations.json instead.','public enum Operations {']
for op in ops:
 out.append('    /// '+op['method']+' '+op['path'])
 out.append('    public static let '+camel(op['name'])+' = Operation(name: '+json.dumps(op['name'])+', method: '+json.dumps(op['method'])+', path: '+json.dumps(op['path'])+', surface: .'+op['surface']+', sources: ['+','.join(json.dumps(s) for s in op['sources'])+'])')
out.append('    public static let all: [Operation] = ['+','.join(camel(o['name']) for o in ops)+']')
for alias,name in [('mcpPost','post_project_id_v1_mcp'),('mcpGet','get_project_id_v1_mcp'),('mcpDelete','delete_project_id_v1_mcp'),('chatCompletionsCreate','post_project_id_endpoint_slug_v1_chat_completions'),('responsesCreate','post_project_id_endpoint_slug_v1_responses'),('modelsList','get_project_id_endpoint_slug_v1_models'),('embeddingsCreate','post_project_id_endpoint_slug_v1_embeddings'),('filesCreate','post_project_id_v1_files')]:
 out.append('    public static let '+alias+' = '+camel(name))
out.append('}')
(root/'Sources/Erebine/Operations.swift').write_text('\n'.join(out)+'\n')

# Project/routing parameters are inherited from Client. RequestOptions retains
# query, headers, JSON, multipart, and arbitrary bytes without schema filtering.
api = ['// Generated by scripts/generate.py. Edit api/operations.json instead.',
       'public struct API: Sendable {', '    let client: Client']
for op in ops:
    params = [p for p in op['parameters'] if p not in ['project_id', 'endpoint_slug']]
    arguments = ''.join(camel(p)+': String, ' for p in params)
    api.append('    /// '+op['method']+' '+op['path'])
    api.append('    public func '+camel(op['name'])+'('+arguments+'options: RequestOptions = .init()) async throws -> APIResponse {')
    if params:
        api.append('        var options = options')
        for p in params:
            api.append('        options.parameters['+json.dumps(p)+'] = '+camel(p))
    api.append('        return try await client.send(Operations.'+camel(op['name'])+', options: options)')
    api.append('    }')
api += ['}', 'extension Client { public var api: API { API(client: self) } }']
(root/'Sources/Erebine/API.swift').write_text('\n'.join(api)+'\n')
